#!/usr/bin/env python3
"""Write DB/forever/QuestPrereqs.lua: what each quest the Forever guides pick
up needs first, from QuestieDB's Forever data. The guide card uses it to skip
pickup steps for quests you can't get yet (no Questie needed in game).

Usage: python3 tools/build_prereqs.py --questiedb <QuestieDB checkout>
"""
import argparse, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import build_route as br

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def guide_files():
    xml = open(os.path.join(ROOT, "Guides", "GuideList-forever.xml")).read()
    return [os.path.join(ROOT, f) for f in re.findall(r'file="([^"]+\.lua)"', xml)]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--questiedb", required=True)
    a = ap.parse_args()
    db = br.load_db(a.questiedb)
    ids = set()
    for f in guide_files():
        for m in re.finditer(r"^\s*\.accept\s+(-?\d+)", open(f).read(), re.M):
            ids.add(abs(int(m.group(1))))
    rows = []
    for qid in sorted(ids):
        row = db["q"].get(qid)
        if not row:
            continue
        q = br.Quest(qid, row)
        parts = []
        if q.preSingle:
            parts.append("any={%s}" % ",".join(str(abs(x)) for x in q.preSingle))
        if q.preGroup:
            parts.append("all={%s}" % ",".join(str(abs(x)) for x in q.preGroup))
        if q.exclusiveTo:
            parts.append("excl={%s}" % ",".join(str(x) for x in q.exclusiveTo))
        if parts:
            rows.append("    [%d] = {%s}, -- %s" % (qid, ", ".join(parts), (q.name or "").replace("\n", " ")))
    out = os.path.join(ROOT, "DB", "forever", "QuestPrereqs.lua")
    with open(out, "w") as fh:
        fh.write("-- Generated by tools/build_prereqs.py from QuestieDB Forever data. Do not edit.\n")
        fh.write("-- any = one of these turned in, all = every one turned in, excl = none of these done\n")
        fh.write("local _, addon = ...\n\naddon.openxpPrereqs = {\n")
        fh.write("\n".join(rows))
        fh.write("\n}\n")
    print("wrote %d of %d quests to %s" % (len(rows), len(ids), out))

if __name__ == "__main__":
    main()
