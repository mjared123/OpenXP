def header(levels):
    return """-- OpenXP Alliance %s for WoW Forever.
-- Generated by tools/build_route.py from Questie's Forever quest data (plus
-- /oxp questdump for Forever's new quests), then meant to be played and
-- hand-tuned. Section levels come from the route builder's level simulation.
local faction = UnitFactionGroup("player")
if faction == "Horde" then return end
local L = GetLocale() if L and RXP.enabledLocale[L] then return end
""" % levels


def fp(name, zone, x, y, master):
    return [
        "step",
        "    .goto %s,%.2f,%.2f" % (zone, x, y),
        "    >>Talk to |cRXP_FRIENDLY_%s|r" % master,
        "    .fp %s >>Get the %s flight path" % (name, name),
        "    .target %s" % master,
    ]


def travel(zone, text):
    return ["step", "    #completewith next", "    .zone %s >>%s" % (zone, text)]


def home(zone, x, y, keeper, town):
    return [
        "step",
        "    .goto %s,%.2f,%.2f" % (zone, x, y),
        "    >>Talk to |cRXP_FRIENDLY_%s|r" % keeper,
        "    .home >>Set your Hearthstone to %s" % town,
        "    .target %s" % keeper,
    ]


