#!/usr/bin/env python3
"""Build OpenXP/Data/Flights.lua: flight masters and flight times, from the
game's own client data tables (TaxiNodes, TaxiPath, TaxiPathNode) as
published by wago.tools.

    python3 tools/build_flights.py [--product wow_classic_era] [--speed 32]

WoW Forever's client isn't on wago.tools, so this uses the Classic Era build;
flight masters that only exist on Forever are learned in game from the
flight map (Nav/Travel.lua records them) and added to this table at run time.

Only real flight masters are kept: nodes with a character bit (the ones you
can learn) on Eastern Kingdoms (0) or Kalimdor (1), with a mount for at
least one faction. A flight's time is the length of its path divided by the
flight speed, plus the waits along it.

World coordinates follow HereBeDragons: wx is the game's Y, wy the game's X.
"""
import csv
import io
import math
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "OpenXP", "Data", "Flights.lua")
URL = "https://wago.tools/db2/%s/csv?product=%s"


def table(name, product):
    req = urllib.request.Request(URL % (name, product), headers={"User-Agent": "openxp-build-flights"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8"))))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv):
    product, speed = "wow_classic_era", 32.0
    i = 0
    while i < len(argv):
        if argv[i] == "--product":
            product = argv[i + 1]
            i += 2
        elif argv[i] == "--speed":
            speed = float(argv[i + 1])
            i += 2
        else:
            raise SystemExit("unknown argument %s" % argv[i])

    nodes = {}
    for row in table("TaxiNodes", product):
        cont = int(row["ContinentID"])
        bit = int(row["CharacterBitNumber"] or 0)
        # MountCreatureID_0 is the Horde mount, _1 the Alliance one
        h, a = int(row["MountCreatureID_0"] or 0), int(row["MountCreatureID_1"] or 0)
        if cont not in (0, 1) or bit <= 0 or not (a or h) or not row["Name_lang"]:
            continue
        faction = "B" if a and h else ("A" if a else "H")
        nodes[int(row["ID"])] = {
            "name": row["Name_lang"], "wx": float(row["Pos_1"]), "wy": float(row["Pos_0"]),
            "inst": cont, "faction": faction,
        }

    paths = {}
    for row in table("TaxiPath", product):
        a, b = int(row["FromTaxiNode"]), int(row["ToTaxiNode"])
        if a in nodes and b in nodes:
            paths[int(row["ID"])] = (a, b)

    points = {}
    for row in table("TaxiPathNode", product):
        pid = int(row["PathID"])
        if pid in paths:
            points.setdefault(pid, []).append(
                (int(row["NodeIndex"]), float(row["Loc_0"]), float(row["Loc_1"]), float(row["Delay"] or 0)))

    times = {}
    for pid, (a, b) in paths.items():
        pts = sorted(points.get(pid, []))
        if len(pts) < 2:
            continue
        length = sum(math.hypot(pts[k][1] - pts[k - 1][1], pts[k][2] - pts[k - 1][2]) for k in range(1, len(pts)))
        wait = sum(p[3] for p in pts)
        times.setdefault(a, {})[b] = int(round(length / speed + wait))

    out = [
        "local _, OXP = ...",
        "",
        "-- Flight masters and flight times. Generated by tools/build_flights.py from",
        "-- the game's client data (TaxiNodes, TaxiPath, TaxiPathNode; %s via" % product,
        "-- wago.tools); don't edit. Forever-only flight masters are learned in game.",
        "-- nodes[id] = {name, wx, wy, inst, faction (A, H or B)}; times[from][to] = seconds.",
        "OXP.flightData = {",
        "    nodes = {",
    ]
    for nid in sorted(nodes):
        n = nodes[nid]
        out.append("        [%d] = { name = %s, wx = %.1f, wy = %.1f, inst = %d, faction = \"%s\" }," % (
            nid, lua_str(n["name"]), n["wx"], n["wy"], n["inst"], n["faction"]))
    out.append("    },")
    out.append("    times = {")
    for a in sorted(times):
        inner = ", ".join("[%d] = %d" % (b, s) for b, s in sorted(times[a].items()))
        out.append("        [%d] = { %s }," % (a, inner))
    out.append("    },")
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d flight masters, %d flights -> %s" % (len(nodes), sum(len(v) for v in times.values()),
                                                  os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
