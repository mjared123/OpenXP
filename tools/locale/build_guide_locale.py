"""Builds locale/<lang>_guide.lua from tools/locale/<lang>/guide.json.

guide.json maps a guide text skeleton (see guide_skeleton.py) to its
translation. Run after adding translations:

    python3 tools/locale/build_guide_locale.py es esES esMX

Prints which guide texts still have no translation (they show in English).
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from guide_skeleton import skeleton, guide_texts  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    lang, locales = sys.argv[1], sys.argv[2:]
    phrases = json.load(open(os.path.join(os.path.dirname(__file__), lang, "guide.json"), encoding="utf-8"))
    guides = sorted(glob.glob(os.path.join(ROOT, "Guides/openxp/*.lua")) +
                    glob.glob(os.path.join(ROOT, "Guides/forever/*.lua")))
    used, missing, total = set(), set(), 0
    for text in guide_texts(guides):
        key, _ = skeleton(text)
        if key is None or key.startswith("/"):
            continue
        total += 1
        if key in phrases:
            used.add(key)
        else:
            missing.add(key)
    cond = " and ".join('loc ~= "%s"' % l for l in locales)
    out = ["-- Generated by tools/locale/build_guide_locale.py from tools/locale/%s/guide.json." % lang,
           "-- Guide step text in this language: see GuideText in Locale.lua. Edit the",
           "-- JSON and run the script again rather than editing this file.",
           "local _, addon = ...",
           "local loc = GetLocale()",
           "if %s then return end" % cond,
           "",
           "addon.guidePhrases = {"]
    for key in sorted(used):
        out.append("[%s] = %s," % (lua_str(key), lua_str(phrases[key])))
    out.append("}")
    # Optional names.json: English name -> this language's name, for names in
    # guide text that NPCnames.lua lacks (loot, objects, [item] links, plurals).
    names_path = os.path.join(os.path.dirname(__file__), lang, "names.json")
    if os.path.exists(names_path):
        names = json.load(open(names_path, encoding="utf-8"))
        out += ["", "addon.guideNames = {"]
        for name in sorted(names):
            out.append("[%s] = %s," % (lua_str(name), lua_str(names[name])))
        out.append("}")
    path = os.path.join(ROOT, "locale", "%s_guide.lua" % locales[0])
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%s: %d phrases, %d untranslated patterns" % (os.path.relpath(path, ROOT), len(used), len(missing)))
    for key in sorted(missing):
        print("  missing:", key)


if __name__ == "__main__":
    main()
