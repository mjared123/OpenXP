"""Generate the French Lua dictionaries from tools/locale/fr/*.json."""
import json
import re
from pathlib import Path

from build_guide_locale import lua_str
from build_ui_locale import BEGIN, END

ROOT = Path(__file__).resolve().parents[2]
CATALOGUES = Path(__file__).resolve().parent / "fr"


def read(name):
    return json.loads((CATALOGUES / name).read_text(encoding="utf-8"))


def write_ui():
    path = ROOT / "locale/frFR.lua"
    source = path.read_text(encoding="utf-8")
    source = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", source, flags=re.S).rstrip()
    ui = read("ui.json")
    lines = [BEGIN]
    lines.extend(f"L[{lua_str(key)}] = {lua_str(value)}" for key, value in sorted(ui.items()))
    lines.append(END)
    path.write_text(source + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(ui)


def write_guides():
    data = read("guide.json")
    lines = [
        "-- Generated by tools/locale/build_fr_locale.py. Edit the French JSON catalogues.",
        "local _, addon = ...",
        'if GetLocale() ~= "frFR" then return end',
    ]
    for key, field in (
        ("guide", "guidePhrases"),
        ("names", "guideNamesFr"),
        ("quests", "guideQuestNames"),
        ("titles", "guideTitles"),
        ("ids", "guideNameIds"),
        ("objectIds", "guideObjectIdsFr"),
        ("objectNames", "guideObjectNamesFr"),
    ):
        lines.extend(("", f"addon.{field} = {{"))
        for english, french in sorted(data[key].items()):
            source = str(int(english)) if key == "quests" else lua_str(english)
            if key == "ids":
                value = "{" + lua_str(french[0]) + ", " + str(french[1]) + "}"
            elif key == "objectIds":
                value = str(french)
            else:
                value = lua_str(french)
            lines.append(f"    [{source}] = {value},")
        lines.append("}")
    lines.extend(("", "-- English guide names matched to NPC IDs in QuestieDB for Forever.",
                  "addon.foreverGuideNpcIds = {"))
    for name, npc_id in sorted(read("forever_npcs.json").items()):
        lines.append(f"    [{lua_str(name)}] = {npc_id},")
    lines.append("}")
    path = ROOT / "locale/frFR_guide.lua"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(data["guide"])


if __name__ == "__main__":
    print(f"French locale: {write_ui()} UI strings, {write_guides()} guide patterns")
