#!/usr/bin/env python3
"""Saved places after a guide rebuild moves steps.

    python3 tools/step_remap.py <old git rev> <version>

Compares each leveling guide's steps at <old git rev> with the files on
disk and writes OpenXP/Data/StepRemap.lua: for every guide whose steps
moved, old step index -> new step index. Engine/StepRemap.lua moves each
character's saved step, skips and statuses once (per <version>). A step
that is gone (moved to another guide) maps to the next step that stayed.
"""
import difflib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["OpenXP/Guides/Leveling/Alliance/PoleStar-01-60.lua", "OpenXP/Guides/Leveling/Horde/PoleStar-01-60.lua"]
OUT = os.path.join(ROOT, "OpenXP", "Data", "StepRemap.lua")


def guides(text):
    """{ "group/name <only>": [step text, ...] } (Registry.lua's guide key)."""
    out, head, steps, buf = {}, None, None, None

    def close():
        if head is not None:
            if buf is not None:
                steps.append(buf)
            key = head["group"] + "/" + head["name"] + (" <%s>" % head["only"] if head.get("only") else "")
            out[key] = steps

    for line in text.splitlines():
        if line == "  {":
            close()
            head, steps, buf = {}, [], None
            continue
        if head is None:
            continue
        m = re.match(r'    (name|group|only) = "(.*)",$', line)
        if m and steps == [] and buf is None:
            head[m.group(1)] = m.group(2)
            continue
        if line.startswith("      {"):
            if buf is not None:
                steps.append(buf)
            buf = line.strip()
        elif buf is not None and line.startswith("        "):
            buf += line.strip()
    close()
    return out


def remap(old, new):
    sm = difflib.SequenceMatcher(None, old, new, autojunk=False)
    m = {}
    for a, b, size in sm.get_matching_blocks():
        for k in range(size):
            m[a + k + 1] = b + k + 1
    full, nxt = [0] * len(old), len(new) + 1
    for i in range(len(old), 0, -1):
        if i in m:
            nxt = m[i]
        full[i - 1] = m.get(i, nxt)
    return full


def main(rev, version):
    lines = ["-- Generated by tools/step_remap.py %s; do not edit." % rev,
             "-- Saved places for guides whose steps moved in %s: [guide key] = { new index of old step 1, 2, ..., old end }." % version,
             "local _, OXP = ...",
             "OXP.StepRemap = {",
             "    version = %s," % version,
             "    guides = {"]
    n = 0
    for f in FILES:
        old = guides(subprocess.run(["git", "-C", ROOT, "show", "%s:%s" % (rev, f)], capture_output=True, text=True, check=True).stdout)
        new = guides(open(os.path.join(ROOT, f), encoding="utf-8").read())
        for key, steps in old.items():
            if key not in new or steps == new[key]:
                continue
            full = remap(steps, new[key]) + [len(new[key]) + 1]  # finished stays finished
            lines.append('        [%s] = { %s },' % (lua_str(key), ", ".join(map(str, full))))
            n += 1
    lines += ["    },", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("%d guides remapped -> %s" % (n, os.path.relpath(OUT, ROOT)))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], int(sys.argv[2]))
