#!/usr/bin/env python3
"""Build OpenXP/Data/Trainers.lua: every class trainer's name and spots, from
forever-db (PoleStar repository, GPL-3.0; credits in OpenXP/NOTICE.md).

    python3 tools/build_trainers.py [--src ../polestar-src/forever-db]

A "train" step has no spot of its own (the guide says "train your new
spells" for every class); with this the arrow leads to your class's
trainer nearest you (GitHub #127).
"""
import collections
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import build_questdb as qb  # noqa: E402

OUT = os.path.join(ROOT, "OpenXP", "Data", "Trainers.lua")
CLASSES = {"Warrior": "WARRIOR", "Paladin": "PALADIN", "Hunter": "HUNTER", "Rogue": "ROGUE", "Priest": "PRIEST",
           "Shaman": "SHAMAN", "Mage": "MAGE", "Warlock": "WARLOCK", "Druid": "DRUID"}


def main(argv):
    src = qb.DEFAULT_SRC
    if argv[:1] == ["--src"]:
        src = argv[1]
    index = json.load(open(os.path.join(src, "index.json"), encoding="utf-8"))
    commit = subprocess.run(["git", "-C", os.path.dirname(src), "rev-parse", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    trainers = {}
    for r in qb.rows(src, "npc"):
        sub = (r.get("subname") or "").strip()
        if sub.endswith(" Trainer") and sub[:-8] in CLASSES and r.get("name"):
            trainers[r["id"]] = (r["name"], CLASSES[sub[:-8]])
    frames = list(qb.rows(src, "ui_map"))

    def to_map(cmap, x, y):
        best = None
        for f in frames:
            if f["map"] != cmap or not (f["right"] <= y <= f["left"] and f["bottom"] <= x <= f["top"]):
                continue
            area = (f["left"] - f["right"]) * (f["top"] - f["bottom"])
            if best is None or area < best[0]:
                best = (area, f)
        if not best:
            return None
        f = best[1]
        return f["ui_map"], (f["left"] - y) / (f["left"] - f["right"]) * 100, (f["top"] - x) / (f["top"] - f["bottom"]) * 100

    spots = collections.defaultdict(list)
    for r in qb.rows(src, "spawn"):
        if r["kind"] == "npc" and r["id"] in trainers:
            m = to_map(r["map"], r["x"], r["y"])
            if m:
                p = (m[0], round(m[1], 2), round(m[2], 2))
                if p not in spots[r["id"]]:
                    spots[r["id"]].append(p)
    by_class = collections.defaultdict(list)
    for nid, (name, cls) in sorted(trainers.items()):
        for m, x, y in spots.get(nid, []):
            by_class[cls].append((nid, name, m, x, y))
    out = [
        "local _, OXP = ...",
        "",
        "-- Class trainers for WoW Forever, generated by tools/build_trainers.py from forever-db",
        "-- (PoleStar repository commit %s, dataset %s). GPL-3.0. Don't edit: rebuild." % (commit[:12], index.get("version")),
        "-- trainers[CLASS] = { {npcID, name, uiMap, x, y}, ... }",
        "OXP.trainers = {",
    ]
    for cls in sorted(by_class):
        out.append("    %s = {" % cls)
        for nid, name, m, x, y in by_class[cls]:
            out.append("        {%d, %s, %d, %g, %g}," % (nid, qb.lua_str(name), m, x, y))
        out.append("    },")
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d trainers, %d spots -> %s" % (len(trainers), sum(len(v) for v in by_class.values()), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
